import { queueAchievementCheck } from '../services/achievementQueue.js';
﻿import express from 'express';
import { prisma } from '../config/prisma.js';
import { authMiddleware,optionalAuthMiddleware } from '../middlewares/auth.js';
import { asyncHandler } from '../middlewares/errorHandler.js';
import { createComments } from '../services/comments.js';
import { announceNotification } from '../utils/notifications.js';
const router=express.Router(),comments=createComments(prisma);
router.get('/:problemId',optionalAuthMiddleware,asyncHandler(async(req,res)=>{const result=await comments.list(req,req.params.problemId,req.query);res.json(req.query.paginated==='true'?result:result.data);}));
router.get('/:problemId/:commentId/replies',optionalAuthMiddleware,asyncHandler(async(req,res)=>res.json(await comments.list(req,req.params.problemId,{...req.query,parentId:req.params.commentId,limit:20}))));
router.post('/:problemId',authMiddleware,asyncHandler(async(req,res)=>{const result=await comments.create(req,req.params.problemId,req.body);queueAchievementCheck(req.userId);for(const notification of result.notifications)void announceNotification(notification).catch(()=>{});res.status(201).json(result.comment);}));
export default router;
